"""
Loads the book catalog from app/catalog_seed.json — generated by
scripts/seed_catalog.py (Open Library + local LLM tagging) and cleaned
up by scripts/apply_corrections.py. See backend/scripts/ for how this
file is built.
"""

import json
from pathlib import Path
from typing import TypedDict, List, Optional

CATALOG_PATH = Path(__file__).parent / "catalog_seed.json"


class Book(TypedDict):
    id: str
    title: str
    author: str
    genres: List[str]
    moods: List[str]
    comp_ids: List[str]
    why_it_works: str
    cover_url: Optional[str]
    first_publish_year: Optional[int]


def _load_catalog() -> List[Book]:
    if not CATALOG_PATH.exists():
        raise FileNotFoundError(
            f"{CATALOG_PATH} not found. Run scripts/seed_catalog.py and "
            "scripts/apply_corrections.py from the backend/ directory first."
        )
    return json.loads(CATALOG_PATH.read_text())


BOOKS: List[Book] = _load_catalog()


def get_book(book_id: str) -> Optional[Book]:
    for b in BOOKS:
        if b["id"] == book_id:
            return b
    return None


def find_by_title(query: str) -> List[Book]:
    q = query.strip().lower()
    if not q:
        return []
    exact = [b for b in BOOKS if b["title"].lower() == q]
    if exact:
        return exact
    return [b for b in BOOKS if q in b["title"].lower()]


ALL_GENRES = sorted({g for b in BOOKS for g in b["genres"]})
ALL_MOODS = sorted({m for b in BOOKS for m in b["moods"]})